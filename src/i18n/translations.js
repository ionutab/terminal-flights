/**
 * Get translation dictionary for a language code (with fallback to 'en')
 * @param {string} langCode
 * @returns {typeof TRANSLATIONS['en']}
 */
export function getTranslations(langCode = "en") {
  if (!langCode || typeof langCode !== "string") {
    return TRANSLATIONS.en;
  }

  const primary = langCode.trim().toLowerCase().split(/[-_]/)[0];
  if (TRANSLATIONS[primary]) {
    return TRANSLATIONS[primary];
  }

  return TRANSLATIONS.en;
}

/**
 * Interpolates placeholders in a translation string: e.g. "{price} on {date}"
 * @param {string} template
 * @param {Record<string, string|number>} values
 * @returns {string}
 */
export function t(template, values = {}) {
  if (!template) return "";
  let res = template;
  for (const [k, v] of Object.entries(values)) {
    res = res.replaceAll(`{${k}}`, String(v));
  }
  return res;
}
